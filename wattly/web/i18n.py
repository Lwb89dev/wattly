def normalize_language(code: str | None) -> str:
    code = (code or "").lower()
    return "it" if code.startswith("it") else "en"


def detect_language(stored: str | None = None) -> str:
    """Resolution: explicit setting > env > OS locale > English."""
    if stored:
        return normalize_language(stored)
    env = os.environ.get("WATTLY_LANGUAGE")
    if env:
        return normalize_language(env)
    try:
        lang = locale.getlocale()[0] or ""
    except ValueError:
        lang = ""
    return normalize_language(lang)


def gettext(key: str, lang: str | None = None, **kwargs) -> str:
    """Translate ``key``; missing keys render as ⟦key⟧ so gaps are visible."""
    language = lang or getattr(g, "wattly_language", None) or "en"
    table = MESSAGES.get(language, MESSAGES["en"])
    text = table.get(key) or MESSAGES["en"].get(key) or f"⟦{key}⟧"
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def js_catalog(lang: str) -> dict[str, str]:
    return {k: gettext(k, lang) for k in JS_KEYS}


def missing_keys(lang: str) -> list[str]:
    """Keys present in English but untranslated in ``lang`` (test helper)."""
    return [k for k in MESSAGES["en"] if k not in MESSAGES.get(lang, {})]
